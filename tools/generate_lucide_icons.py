"""Regenerate the checked-in ImGui vector data from vendored Lucide path geometry.

Requires fonttools for developer-side regeneration only; builds need no Python or SVG parser.
"""
from __future__ import annotations

import argparse
import pathlib
from fontTools.pens.recordingPen import RecordingPen
from fontTools.svgLib.path import parse_path

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/icons/lucide.paths'
TARGET = ROOT / 'src/app/ui_lucide_data.h'


def fmt(n: float) -> str:
    if abs(n) < 0.000005:
        n = 0.0
    s = f'{n:.5f}'.rstrip('0').rstrip('.')
    return f'{s}.0f' if '.' not in s else f'{s}f'


def rect_path(x: float, y: float, w: float, h: float, rad: float) -> str:
    r = min(max(rad, 0.0), w * .5, h * .5)
    if r == 0:
        return f'M{x} {y}h{w}v{h}h{-w}Z'
    return (f'M{x+r} {y}H{x+w-r}a{r} {r} 0 0 1 {r} {r}'
            f'V{y+h-r}a{r} {r} 0 0 1 {-r} {r}'
            f'H{x+r}a{r} {r} 0 0 1 {-r} {-r}'
            f'V{y+r}a{r} {r} 0 0 1 {r} {-r}Z')


def circle_path(x: float, y: float, r: float) -> str:
    return f'M{x+r} {y}a{r} {r} 0 1 1 {-2*r} 0a{r} {r} 0 1 1 {2*r} 0Z'


def pen_to_paths(pen: RecordingPen) -> list[list[tuple]]:
    paths: list[list[tuple]] = []
    current: list[tuple] = []
    pos = (0.0, 0.0)
    for name, args in pen.value:
        if name == 'moveTo':
            if current:
                paths.append(current)
            current = [('M', *args[0])]
            pos = args[0]
        elif name == 'lineTo':
            current.append(('L', *args[0]))
            pos = args[0]
        elif name == 'curveTo':
            for i in range(0, len(args), 3):
                a, b, c = args[i:i+3]
                current.append(('C', *a, *b, *c))
                pos = c
        elif name == 'qCurveTo':
            # Lucide currently does not use quadratic curves, but handle them if it does.
            for point in args[:-1]:
                end = args[-1]
                c1 = tuple(pos[i] + (point[i] - pos[i]) * (2.0/3.0) for i in range(2))
                c2 = tuple(end[i] + (point[i] - end[i]) * (2.0/3.0) for i in range(2))
                current.append(('C', *c1, *c2, *end))
                pos = end
        elif name == 'closePath':
            current.append(('Z',))
            paths.append(current)
            current = []
        elif name == 'endPath':
            if current:
                paths.append(current)
            current = []
        else:
            raise ValueError(f'unhandled SVG operation: {name}')
    if current:
        paths.append(current)
    return paths


def parse_shapes(shape: str) -> list[list[tuple]]:
    if shape.startswith('P'):
        path = shape[1:]
    elif shape.startswith('R'):
        x, y, w, h, r = map(float, shape[1:].split(','))
        path = rect_path(x, y, w, h, r)
    elif shape.startswith('C'):
        x, y, r = map(float, shape[1:].split(','))
        path = circle_path(x, y, r)
    else:
        raise ValueError(f'unsupported Lucide shape: {shape}')
    pen = RecordingPen()
    parse_path(path, pen)
    return pen_to_paths(pen)


def format_ops(data: list[tuple]) -> str:
    lines = []
    for cmd in data:
        key, *xy = cmd
        values = [fmt(float(v)) for v in xy]
        values.extend(['0.0f'] * (6 - len(values)))
        lines.append('    {' + ', '.join([f"'{key}'", *values]) + '},')
    return '\n'.join(lines)


def build() -> str:
    entries = [line.strip() for line in SOURCE.read_text().splitlines() if line.strip()]
    all_ops: list[tuple] = []
    paths: list[tuple[int, int]] = []
    glyphs: list[tuple[str, int, int]] = []
    seen = set()
    for entry in entries:
        name, source = entry.split('=', 1)
        if name in seen:
            raise ValueError(f'duplicate icon {name}')
        seen.add(name)
        start = len(paths)
        for shape in source.split('|'):
            for ops in parse_shapes(shape):
                if not ops or ops[0][0] != 'M':
                    raise ValueError(f'invalid contour for {name}: {ops}')
                paths.append((len(all_ops), len(ops)))
                all_ops.extend(ops)
        glyphs.append((name, start, len(paths) - start))
    rows = [
        '// SPDX-License-Identifier: ISC',
        '// Generated by tools/generate_lucide_icons.py from Lucide outlines.',
        '#pragma once',
        '',
        '#include <cstddef>',
        '#include <cstdint>',
        '',
        'namespace noise::app::ui_icons::data {',
        'struct Op { char type; float a, b, c, d, e, f; };',
        'struct Path { std::uint32_t first, count; };',
        'struct Glyph { std::uint32_t first, count; };',
        '',
        'inline constexpr Op ops[] = {',
        format_ops(all_ops),
        '};',
        'inline constexpr Path paths[] = {',
        '\n'.join(f'    {{{a}u, {b}u}},' for a, b in paths),
        '};',
        'inline constexpr Glyph glyphs[] = {',
        '\n'.join(f'    {{{a}u, {b}u}}, // {name}' for name, a, b in glyphs),
        '};',
        f'inline constexpr std::size_t glyph_count = {len(glyphs)};',
        '} // namespace noise::app::ui_icons::data',
        '',
    ]
    return '\n'.join(rows)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = build()
    if args.check:
        if TARGET.read_text() != generated:
            raise SystemExit('Generated Lucide header is out of date')
        print('Lucide data is current')
    else:
        TARGET.write_text(generated)
        print(f'Generated {TARGET} ({len(generated)} bytes)')


if __name__ == '__main__':
    main()
